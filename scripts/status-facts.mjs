/**
 * status-facts.mjs -- the facts about each package that can be derived from the
 * tree, kept in docs/security.md between two markers and checked by
 * `npm test` (scripts/status-facts.test.mjs), so the document cannot drift from
 * the code on these points. The judgements ("implemented", "partial", what is
 * and is not protected) stay hand-written; the check only requires that every
 * package has a row in the status table and every row names a package.
 *
 *   node scripts/status-facts.mjs           check docs/security.md (exit 1 on a difference)
 *   node scripts/status-facts.mjs --write   rewrite the generated block
 *
 * Facts per package under `packages/`: whether it is published (the version is
 * collected but deliberately not rendered, so the automated version-packages
 * pull request does not fail this check), the
 * entry points of its `package.json` `exports` (`.` when there are none), the
 * number of `*.test.mjs` files under `test/` (shown only as yes/no, so adding a
 * test file does not change the document), whether `test/real-peer/` exists
 * (native WebRTC peers, `npm run test:real-peer`) and whether anything under
 * `tests/browser/` names the package (the real-browser suite).
 */

import { readdir, readFile, writeFile, stat } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const BEGIN_MARKER = '<!-- status-facts:begin (generated by scripts/status-facts.mjs; do not edit by hand) -->'
export const END_MARKER = '<!-- status-facts:end -->'

/** @param {string} dir @returns {Promise<string[]>} every file path under dir, skipping node_modules */
async function walk(dir) {
  let entries
  try { entries = await readdir(dir, { withFileTypes: true }) } catch { return [] }
  const out = []
  for (const entry of entries) {
    if (entry.name === 'node_modules') continue
    const path = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...await walk(path))
    else out.push(path)
  }
  return out
}

/** @param {string} path */
async function isDirectory(path) {
  try { return (await stat(path)).isDirectory() } catch { return false }
}

/**
 * @param {string} root repository root
 * @returns {Promise<Array<{dir: string, name: string, version: string, private: boolean, entryPoints: string[], testFiles: number, realPeer: boolean, realBrowser: boolean}>>}
 */
export async function collectFacts(root) {
  const packagesDir = join(root, 'packages')
  const dirs = (await readdir(packagesDir, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name).sort()
  const browserText = []
  for (const file of await walk(join(root, 'tests', 'browser'))) {
    if (/\.(m?js|ts|json|html)$/.test(file)) browserText.push(await readFile(file, 'utf8'))
  }
  const browserSources = browserText.join('\n')

  const facts = []
  for (const dir of dirs) {
    let manifest
    try { manifest = JSON.parse(await readFile(join(packagesDir, dir, 'package.json'), 'utf8')) } catch { continue }
    const exportsField = manifest.exports
    const entryPoints = exportsField && typeof exportsField === 'object' && !Array.isArray(exportsField)
      ? Object.keys(exportsField).filter((key) => key === '.' || key.startsWith('./'))
      : ['.']
    const testFiles = (await walk(join(packagesDir, dir, 'test'))).filter((f) => f.endsWith('.test.mjs')).length
    facts.push({
      dir,
      name: manifest.name ?? dir,
      version: String(manifest.version ?? ''),
      private: manifest.private === true,
      entryPoints,
      testFiles,
      realPeer: await isDirectory(join(packagesDir, dir, 'test', 'real-peer')),
      realBrowser: new RegExp(`${dir}(?![A-Za-z0-9-])`).test(browserSources),
    })
  }
  return facts
}

/** @param {Awaited<ReturnType<typeof collectFacts>>} facts @returns {string} */
export function renderFactsTable(facts) {
  const lines = [
    '| Package | Published | Entry points | Unit tests | Real-peer tests | Real-browser tests |',
    '| --- | --- | --- | --- | --- | --- |',
  ]
  for (const f of facts) {
    // Not the version: the release workflow bumps versions in a pull request of its own, which this check must not fail.
    const version = f.private ? 'private' : 'yes'
    const entries = f.entryPoints.map((e) => `\`${e}\``).join(' ')
    lines.push(`| \`${f.dir}\` | ${version} | ${entries} | ${f.testFiles > 0 ? 'yes' : 'no'} | ${f.realPeer ? 'yes' : 'no'} | ${f.realBrowser ? 'yes' : 'no'} |`)
  }
  return lines.join('\n')
}

/** @param {string} document @returns {{before: string, block: string, after: string}|null} */
function splitAtMarkers(document) {
  const start = document.indexOf(BEGIN_MARKER)
  const end = document.indexOf(END_MARKER)
  if (start === -1 || end === -1 || end < start) return null
  return {
    before: document.slice(0, start + BEGIN_MARKER.length),
    block: document.slice(start + BEGIN_MARKER.length, end).replace(/^\n|\n$/g, ''),
    after: document.slice(end),
  }
}

/** @param {string} document @param {string} table @returns {string} */
export function replaceFactsBlock(document, table) {
  const parts = splitAtMarkers(document)
  if (!parts) throw new Error('docs/security.md has no status-facts markers')
  return `${parts.before}\n${table}\n${parts.after}`
}

/**
 * @param {{root: string, document: string}} opts
 * @returns {Promise<{problems: string[]}>}
 */
export async function checkStatusDocument({ root, document }) {
  const problems = []
  const facts = await collectFacts(root)
  const parts = splitAtMarkers(document)
  if (!parts) {
    problems.push('the status-facts markers are missing from the document')
  } else if (parts.block !== renderFactsTable(facts)) {
    problems.push('the generated facts are out of date (node scripts/status-facts.mjs --write)')
  }

  // The hand-written table: first column of rows under "| Package | Status | Notes |".
  const header = document.indexOf('| Package | Status | Notes |')
  const rows = new Set()
  if (header !== -1) {
    for (const line of document.slice(header).split('\n').slice(2)) {
      if (!line.startsWith('|')) break
      const match = /^\| `([^`]+)` \|/.exec(line)
      if (match) rows.add(match[1])
    }
  } else {
    problems.push('the status table ("| Package | Status | Notes |") is missing')
  }
  const known = new Set(facts.map((f) => f.dir))
  for (const dir of known) if (header !== -1 && !rows.has(dir)) problems.push(`${dir} has no row in the status table`)
  for (const name of rows) if (!known.has(name) && !name.includes('/')) problems.push(`${name} has a row in the status table but there is no such package`)
  return { problems }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = fileURLToPath(new URL('..', import.meta.url))
  const path = join(root, 'docs', 'security.md')
  const document = await readFile(path, 'utf8')
  if (process.argv.includes('--write')) {
    await writeFile(path, replaceFactsBlock(document, renderFactsTable(await collectFacts(root))))
    process.stdout.write('docs/security.md: generated facts rewritten\n')
  } else {
    const { problems } = await checkStatusDocument({ root, document })
    for (const problem of problems) process.stderr.write(`docs/security.md: ${problem}\n`)
    process.exit(problems.length === 0 ? 0 : 1)
  }
}
