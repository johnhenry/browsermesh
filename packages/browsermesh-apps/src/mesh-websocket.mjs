/**
 * A standard-`WebSocket`-instance-shaped class over a persistent mesh
 * envelope channel. See this file's module doc comment for the full
 * wire-protocol/binary-encoding/send-semantics writeup.
 */
export class BrowserMeshWebSocket {
  static CONNECTING = CONNECTING
  static OPEN = OPEN
  static CLOSING = CLOSING
  static CLOSED = CLOSED

  /** @type {{podId?: string, sendTo: Function, onIncomingData: Function}} */
  #peerNode
  /** @type {string} */
  #envelopeType
  /** @type {string} */
  #connectionId
  /** @type {string} Target/remote podId this connection is with. */
  #remotePodId
  /** @type {string} */
  #path
  /** @type {(() => void)|null} */
  #unsubscribe = null
  /** @type {number} */
  #readyState = CONNECTING
  /** @type {ReturnType<typeof setTimeout>|null} */
  #openTimer = null
  /** @type {Record<string, Set<Function>>} */
  #listeners = { open: new Set(), message: new Set(), error: new Set(), close: new Set() }

  /** Settable standard event-handler properties, matching real `WebSocket`. */
  onopen = null
  onmessage = null
  onerror = null
  onclose = null

  /**
   * @param {string} url - `mesh://podId/path`-shaped (or `https://podId.mesh.local/path`),
   *   parsed via `parseMeshRequest()`. Ignored on the internal accepted-session path.
   * @param {object} opts
   * @param {{podId?: string, sendTo: (pubKey: string, data: object) => Promise<void>,
   *   onIncomingData: (cb: (pubKey: string, data: object) => void) => (() => void)}} opts.peerNode
   *   Required (unless constructing via the internal accepted-session path).
   * @param {object} [opts.headers]
   * @param {string} [opts.envelopeType='mesh-websocket']
   * @param {number} [opts.openTimeoutMs=10000]
   * @param {string} [opts.connectionId]
   */
  constructor(url, opts = {}) {
    if (opts[ACCEPTED_SESSION]) {
      const { peerNode, envelopeType, connectionId, remotePodId, path } = opts[ACCEPTED_SESSION]
      this.url = url
      this.#peerNode = peerNode
      this.#envelopeType = envelopeType
      this.#connectionId = connectionId
      this.#remotePodId = remotePodId
      this.#path = path
      this.#readyState = OPEN
      this.#subscribe()
      return
    }

    const {
      peerNode,
      headers = {},
      envelopeType = DEFAULT_ENVELOPE_TYPE,
      openTimeoutMs = DEFAULT_OPEN_TIMEOUT_MS,
      connectionId,
    } = opts

    if (!peerNode || typeof peerNode.sendTo !== 'function' || typeof peerNode.onIncomingData !== 'function') {
      throw new Error('BrowserMeshWebSocket: opts.peerNode is required and must provide sendTo()/onIncomingData()')
    }
    const parsed = parseMeshRequest(url)
    if (!parsed) {
      throw new Error(`BrowserMeshWebSocket: invalid mesh URL '${url}' (expected mesh://podId/path or https://podId.mesh.local/path)`)
    }

    this.url = url
    this.#peerNode = peerNode
    this.#envelopeType = envelopeType
    this.#remotePodId = parsed.podId
    this.#path = parsed.path
    this.#connectionId = connectionId || nextConnectionId(peerNode.podId)
    this.#readyState = CONNECTING

    this.#subscribe()

    this.#openTimer = setTimeout(() => {
      if (this.#readyState !== CONNECTING) return
      this.#dispatch('error', { type: 'error', message: `BrowserMeshWebSocket: open handshake to ${this.#remotePodId} timed out after ${openTimeoutMs}ms` })
      this.#finalizeClose(1006, 'open handshake timed out')
    }, openTimeoutMs)

    Promise.resolve(this.#peerNode.sendTo(this.#remotePodId, {
      type: this.#envelopeType,
      kind: 'ws-open',
      connectionId: this.#connectionId,
      path: this.#path,
      headers,
    })).catch((err) => {
      if (this.#readyState !== CONNECTING) return
      this.#dispatch('error', { type: 'error', message: err?.message || String(err) })
      this.#finalizeClose(1006, 'failed to send open handshake')
    })
  }

  /** @returns {number} One of `CONNECTING`/`OPEN`/`CLOSING`/`CLOSED` (0/1/2/3). */
  get readyState() {
    return this.#readyState
  }

  /** @returns {string} The connection's path, as parsed from the URL (or supplied by the accepting service) -- additive metadata beyond the standard `WebSocket` surface, not a removal of anything standard. */
  get path() {
    return this.#path
  }

  /** @returns {string} The remote peer's podId this connection is with -- additive metadata, see `path`'s doc comment. */
  get remotePodId() {
    return this.#remotePodId
  }

  // -----------------------------------------------------------------------
  // Inbound dispatch
  // -----------------------------------------------------------------------

  #subscribe() {
    this.#unsubscribe = this.#peerNode.onIncomingData((fromPubKey, data) => {
      if (!data || typeof data !== 'object') return
      if (data.type !== this.#envelopeType || data.connectionId !== this.#connectionId) return
      this.#handleEnvelope(fromPubKey, data)
    })
  }

  /** @param {string} fromPubKey @param {object} data */
  #handleEnvelope(fromPubKey, data) {
    switch (data.kind) {
      case 'ws-open-ack': {
        if (this.#readyState !== CONNECTING) return
        if (this.#openTimer) clearTimeout(this.#openTimer)
        this.#readyState = OPEN
        this.#dispatch('open', { type: 'open' })
        return
      }
      case 'ws-reject': {
        if (this.#readyState !== CONNECTING) return
        if (this.#openTimer) clearTimeout(this.#openTimer)
        this.#dispatch('error', { type: 'error', message: data.reason || 'connection rejected' })
        this.#finalizeClose(typeof data.code === 'number' ? data.code : 4403, data.reason || 'rejected')
        return
      }
      case 'ws-message': {
        if (this.#readyState !== OPEN) return
        let payload
        if (data.encoding === 'binary') {
          if (typeof data.data !== 'string') return
          payload = toFreshArrayBuffer(fromBase64(data.data))
        } else {
          payload = data.data
        }
        this.#dispatch('message', { type: 'message', data: payload })
        return
      }
      case 'ws-close': {
        if (this.#readyState === CLOSED) return
        this.#finalizeClose(typeof data.code === 'number' ? data.code : 1000, data.reason || '')
        return
      }
      default:
        return
    }
  }

  // -----------------------------------------------------------------------
  // Standard methods
  // -----------------------------------------------------------------------

  /**
   * @param {string|ArrayBuffer|ArrayBufferView} data
   * @throws {DOMException} `InvalidStateError` if `readyState` is not `OPEN`
   *   (see module doc comment's send-semantics section for why this is true
   *   both before open AND after close, the latter a deliberate deviation
   *   from the WHATWG spec).
   */
  send(data) {
    if (this.#readyState !== OPEN) {
      throw invalidStateError(`BrowserMeshWebSocket.send() called while readyState is ${this.#readyState} (must be OPEN)`)
    }

    let payload
    if (typeof data === 'string') {
      payload = { encoding: 'text', data }
    } else if (data instanceof ArrayBuffer) {
      payload = { encoding: 'binary', data: toBase64(new Uint8Array(data)) }
    } else if (ArrayBuffer.isView(data)) {
      payload = { encoding: 'binary', data: toBase64(new Uint8Array(data.buffer, data.byteOffset, data.byteLength)) }
    } else {
      throw new TypeError('BrowserMeshWebSocket.send(): data must be a string, ArrayBuffer, or ArrayBuffer view (Blob is not supported -- see module doc comment)')
    }

    Promise.resolve(this.#peerNode.sendTo(this.#remotePodId, {
      type: this.#envelopeType,
      kind: 'ws-message',
      connectionId: this.#connectionId,
      ...payload,
    })).catch((err) => {
      this.#dispatch('error', { type: 'error', message: err?.message || String(err) })
    })
  }

  /**
   * @param {number} [code=1000]
   * @param {string} [reason='']
   */
  close(code = 1000, reason = '') {
    if (this.#readyState === CLOSING || this.#readyState === CLOSED) return
    this.#readyState = CLOSING
    Promise.resolve(this.#peerNode.sendTo(this.#remotePodId, {
      type: this.#envelopeType,
      kind: 'ws-close',
      connectionId: this.#connectionId,
      code,
      reason,
    })).catch(() => {
      // Best-effort notification -- see module doc comment's "one-directional,
      // not a two-phase closing handshake" reasoning. Nothing further to do
      // if the peer is already unreachable; we still finalize our own side.
    }).finally(() => {
      this.#finalizeClose(code, reason)
    })
  }

  /** @param {number} code @param {string} reason */
  #finalizeClose(code, reason) {
    if (this.#readyState === CLOSED) return
    this.#readyState = CLOSED
    if (this.#openTimer) {
      clearTimeout(this.#openTimer)
      this.#openTimer = null
    }
    if (this.#unsubscribe) {
      this.#unsubscribe()
      this.#unsubscribe = null
    }
    this.#dispatch('close', { type: 'close', code, reason, wasClean: true })
  }

  // -----------------------------------------------------------------------
  // Event dispatch: onX properties AND addEventListener()-registered listeners
  // -----------------------------------------------------------------------

  /** @param {'open'|'message'|'error'|'close'} type @param {object} event */
  #dispatch(type, event) {
    const handler = this[`on${type}`]
    if (typeof handler === 'function') {
      try {
        handler.call(this, event)
      } catch {
        // A throwing handler must never break this class's own internal
        // state machine -- matches real EventTarget dispatch semantics
        // (a listener throwing does not stop other listeners/handlers).
      }
    }
    const set = this.#listeners[type]
    if (!set) return
    for (const cb of [...set]) {
      try {
        cb.call(this, event)
      } catch {
        // Same reasoning as above.
      }
    }
  }

  /** @param {'open'|'message'|'error'|'close'} type @param {Function} listener */
  addEventListener(type, listener) {
    const set = this.#listeners[type]
    if (!set || typeof listener !== 'function') return
    set.add(listener)
  }

  /** @param {'open'|'message'|'error'|'close'} type @param {Function} listener */
  removeEventListener(type, listener) {
    const set = this.#listeners[type]
    if (!set) return
    set.delete(listener)
  }
}

