/**
 * Build an already-`OPEN` `BrowserMeshWebSocket`-shaped handle for an
 * ACCEPTED inbound connection, via the internal-only construction path (see
 * `ACCEPTED_SESSION` above). Not exported.
 *
 * @param {object} opts
 * @param {object} opts.peerNode - The raw `peerNode` (not `ctx`) -- needed
 *   because `BrowserMeshWebSocket` subscribes via the single-callback
 *   `peerNode.onIncomingData(cb)` shape, not `ctx`'s type-filtered
 *   `onIncomingData(types, cb)` shape.
 * @param {string} opts.envelopeType
 * @param {string} opts.connectionId
 * @param {string} opts.remotePodId
 * @param {string} opts.path
 * @returns {BrowserMeshWebSocket}
 */
function createAcceptedSession({ peerNode, envelopeType, connectionId, remotePodId, path }) {
  const url = `mesh://${remotePodId}${path}`
  return new BrowserMeshWebSocket(url, {
    [ACCEPTED_SESSION]: { peerNode, envelopeType, connectionId, remotePodId, path },
  })
}

/**
 * Build a `MeshService` descriptor (`mesh-service.mjs`, Phase C) that lets a
 * pod ACCEPT inbound `BrowserMeshWebSocket` connections and originate
 * outbound ones via its `api`. See this file's module doc comment for the
 * full protocol/authorization writeup.
 *
 * @param {object} [opts]
 * @param {(fromPubKey: string, path: string) => boolean|Promise<boolean>} [opts.onConnection]
 *   Accept/reject hook for inbound connections. If omitted, EVERY inbound
 *   connection is rejected -- see module doc comment's "NO onConnection
 *   HANDLER REGISTERED" section. A thrown/rejected hook is treated as a
 *   rejection, never an unhandled rejection.
 * @param {(session: BrowserMeshWebSocket, info: {fromPubKey: string, path: string}) => void} [opts.onIncomingConnection]
 *   Called once per ACCEPTED inbound connection, with an already-`OPEN`
 *   `BrowserMeshWebSocket`-shaped handle for that session (same
 *   send/close/onmessage/addEventListener surface).
 * @param {string} [opts.envelopeType='mesh-websocket']
 * @param {Function} [opts.onLog]
 * @returns {import('./mesh-service.mjs').MeshService}
 */
export function createMeshWebSocketService({
  onConnection,
  onIncomingConnection,
  envelopeType = DEFAULT_ENVELOPE_TYPE,
  onLog,
} = {}) {
  const log = onLog || (() => {})

  return {
    name: 'mesh-websocket',

    attach(peerNode, ctx) {
      const unsubscribe = ctx.onIncomingData(envelopeType, (fromPubKey, msg) => {
        if (!msg || msg.kind !== 'ws-open') return
        handleOpen(fromPubKey, msg).catch((err) => {
          log('mesh-websocket:open-handling-failed', { from: fromPubKey, connectionId: msg.connectionId, error: err?.message || String(err) })
        })
      })

      /** @param {string} fromPubKey @param {object} msg */
      async function handleOpen(fromPubKey, msg) {
        const { connectionId, path } = msg
        let accepted = false
        let rejectReason = 'no onConnection handler registered'

        if (typeof onConnection === 'function') {
          try {
            accepted = await onConnection(fromPubKey, path)
            rejectReason = 'connection rejected'
          } catch (err) {
            log('mesh-websocket:onConnection-threw', { from: fromPubKey, connectionId, error: err?.message || String(err) })
            accepted = false
            rejectReason = err?.message || 'onConnection threw'
          }
        }

        if (!accepted) {
          await ctx.sendTo(fromPubKey, envelopeType, { kind: 'ws-reject', connectionId, code: 4403, reason: rejectReason }).catch((err) => {
            log('mesh-websocket:reject-send-failed', { to: fromPubKey, connectionId, error: err?.message || String(err) })
          })
          return
        }

        const session = createAcceptedSession({ peerNode, envelopeType, connectionId, remotePodId: fromPubKey, path })

        // `onIncomingConnection` is called BEFORE the ack is sent (not
        // after), and synchronously -- deliberately. Sending the ack first
        // yields to the event loop (`await ctx.sendTo()`), and a fast
        // remote peer can react to its own `onopen` and send a message
        // before this continuation resumes; if the application hadn't
        // attached its `onmessage`/etc. handlers to `session` yet at that
        // point, the message is lost. Calling this synchronously, before
        // any `await`, guarantees the application has had a chance to wire
        // up handlers before the ack (and therefore before any reply) can
        // possibly reach the other side. If the ack send below fails, the
        // application already has `session` and will observe the failure
        // via `onclose` (1011) rather than silently never learning the
        // connection was attempted.
        if (typeof onIncomingConnection === 'function') {
          onIncomingConnection(session, { fromPubKey, path })
        }

        try {
          await ctx.sendTo(fromPubKey, envelopeType, { kind: 'ws-open-ack', connectionId })
        } catch (err) {
          log('mesh-websocket:ack-send-failed', { to: fromPubKey, connectionId, error: err?.message || String(err) })
          session.close(1011, 'failed to acknowledge open')
        }
      }

      const api = {
        /**
         * Originate an outbound connection from this peer, equivalent to
         * `new BrowserMeshWebSocket(url, {peerNode, envelopeType, ...connectOpts})`.
         * A thin convenience so a caller that already attached this service
         * (e.g. to also accept inbound connections) doesn't need to
         * separately import the class and re-pass `peerNode`.
         * @param {string} url
         * @param {object} [connectOpts]
         * @returns {BrowserMeshWebSocket}
         */
        connect(url, connectOpts = {}) {
          return new BrowserMeshWebSocket(url, { peerNode, envelopeType, ...connectOpts })
        },
      }

      return {
        api,
        teardown() {
          unsubscribe()
        },
      }
    },
  }
}

export { DEFAULT_ENVELOPE_TYPE, DEFAULT_OPEN_TIMEOUT_MS, CONNECTING, OPEN, CLOSING, CLOSED }
