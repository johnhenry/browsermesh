/**
 * mesh-websocket.mjs -- Phase 3 of the BrowserMeshFetch/BrowserMeshWebSocket
 * plan (`browsermesh-fetch-websocket.md`; independent of, and does not
 * import, Phase 2's `mesh-fetch.mjs` -- both depend only on the same
 * `MeshService` convention and `parseMeshRequest()`, not on each other).
 *
 * Provides `BrowserMeshWebSocket`, a class implementing the standard
 * `WebSocket` INSTANCE surface (`readyState`, `url`, `onopen`/`onmessage`/
 * `onerror`/`onclose`, `addEventListener`/`removeEventListener`, `send()`,
 * `close()`) over a persistent envelope channel addressed by podId, using
 * `mesh://podId/path`-shaped URLs parsed via
 * `@johnhenry/browsermesh-discovery`'s `parseMeshRequest()` (the same parser
 * `sw-routing.mjs`'s `MeshFetchRouter` and Phase 2's `browserMeshFetch()`
 * both use), and `createMeshWebSocketService()`, a `MeshService` (Phase C,
 * `mesh-service.mjs`) that lets a pod ACCEPT inbound connections.
 *
 * ---------------------------------------------------------------------------
 * DEVIATION FROM THE REAL `WebSocket` CONSTRUCTOR (stated up front, per the
 * plan's own framing -- "make the deviation as small and sensible as
 * possible"): a real `new WebSocket(url, protocols)` needs no extra
 * arguments because the browser's networking stack is a process-wide
 * ambient resource. There is no equivalent ambient mesh connection here --
 * `new BrowserMeshWebSocket(url, opts)` therefore requires
 * `opts.peerNode`, a duck-typed object exposing `podId`, `sendTo(pubKey,
 * data)`, and `onIncomingData(cb)` (exactly the subset of the real
 * `PeerNode`'s API this family's other `MeshService`s/tests already rely on
 * -- see `mesh-rpc.mjs`'s test fixtures). This is the ONE required
 * deviation; everything else on the constructed instance matches the
 * standard `WebSocket` instance shape as closely as this transport allows.
 * `opts` also accepts:
 *   - `headers` (object, default `{}`) -- forwarded as connection metadata
 *     on the open handshake, mirroring `mesh-rpc.mjs`'s `headers` field.
 *   - `envelopeType` (string, default `'mesh-websocket'`) -- the shared
 *     `onIncomingData()` dispatch-bus `type`, matching every other
 *     `MeshService` in this family.
 *   - `openTimeoutMs` (number, default 10000) -- see "OPEN TIMEOUT" below.
 *   - `connectionId` (string, optional) -- override the generated
 *     correlation id; only useful for tests wanting deterministic ids.
 *
 * NOTE: unlike every OTHER `MeshService` in this family, a client-role
 * `BrowserMeshWebSocket` does NOT need `createMeshWebSocketService()`
 * attached on the CALLING peer at all -- it subscribes directly to
 * `peerNode.onIncomingData()` and calls `peerNode.sendTo()` itself,
 * filtering by its own `connectionId` (the same envelope-type + extra-field
 * filtering `mesh-service.mjs`'s `ctx.onIncomingData()` does for `type`
 * alone, just one field finer-grained). This keeps `new
 * BrowserMeshWebSocket(url, {peerNode})` usable standalone, matching real
 * `new WebSocket(url)` usage as closely as possible -- a caller should not
 * have to separately construct and attach a `MeshService` just to originate
 * an outbound connection. The RESPONDING side, in contrast, genuinely needs
 * `createMeshWebSocketService({onConnection})` attached, because deciding
 * whether to accept an INBOUND connection this peer didn't initiate is
 * exactly the kind of policy decision every other `MeshService` in this
 * family (`onRequest`, `onGrantChange`, etc.) also delegates to a
 * caller-supplied hook rather than deciding unilaterally.
 *
 * ---------------------------------------------------------------------------
 * WIRE PROTOCOL -- one envelope `type` (default `'mesh-websocket'`), five
 * message `kind`s, every message carrying the `connectionId` that
 * correlates it to one logical connection (generated by the connection's
 * ORIGINATOR -- the client -- exactly like `mesh-rpc.mjs`'s `requestId`):
 *
 *   Open handshake (client -> target podId), sent once at construction:
 *     `{ type, kind: 'ws-open', connectionId, path, headers }`
 *
 *   Accept (target -> client), sent once the target's `onConnection` hook
 *   returns/resolves truthy:
 *     `{ type, kind: 'ws-open-ack', connectionId }`
 *
 *   Reject (target -> client), sent once `onConnection` returns/resolves
 *   falsy, throws, or is not registered at all (see "NO onConnection
 *   HANDLER" below):
 *     `{ type, kind: 'ws-reject', connectionId, code, reason }`
 *
 *   Message (either direction, free-form, any number of times once OPEN):
 *     `{ type, kind: 'ws-message', connectionId, encoding: 'text'|'binary', data }`
 *       -- see "BINARY ENCODING" below for what `data` holds under each
 *       `encoding`.
 *
 *   Close (either direction, at most meaningfully once per side):
 *     `{ type, kind: 'ws-close', connectionId, code, reason }`
 *       -- ONE-DIRECTIONAL notification, not a two-phase closing handshake
 *       like real WebSocket's (client FIN / server FIN / TCP close). The
 *       side that calls `close()` sends this envelope best-effort (a send
 *       failure, e.g. the peer already disconnected, is swallowed -- there
 *       is nothing further to do) and transitions itself to `CLOSED`
 *       immediately afterward, without waiting for any acknowledgement.
 *       The receiving side transitions to `CLOSED` the moment this envelope
 *       arrives. This is the plan's own explicitly sanctioned "keep it
 *       minimal" choice (see the plan's Phase 3 section: "mirrors
 *       grant-log.mjs's [...] initial exchange only if a real security need
 *       is identified -- otherwise keep it minimal"): no real security
 *       property depends on a slower, acknowledged close, and a persistent
 *       mesh envelope channel has no TCP-level half-open state to model in
 *       the first place.
 *
 * ---------------------------------------------------------------------------
 * ACCEPT/REJECT HANDSHAKE AND AUTHORIZATION (mirrors `mesh-rpc.mjs`'s own
 * stance almost exactly): `createMeshWebSocketService({onConnection})`'s
 * `onConnection(fromPubKey, path) -> boolean|Promise<boolean>` hook is the
 * ONLY place accept/reject policy lives. This file does not check
 * `registry.checkAccess()` against any fixed resource/scope -- like
 * mesh-RPC, a persistent duplex channel has no fixed resource this
 * transport could hardcode a scope for; deciding which `(fromPubKey, path)`
 * combinations are acceptable is the RESPONDING POD's own concern, not this
 * transport's, exactly mirroring `mesh-rpc.mjs`'s "authorization is
 * explicitly out of scope for this transport" stance. A caller that needs
 * ACL-gated WebSocket connections should implement that inside its own
 * `onConnection` (e.g. calling `ctx.registry.checkAccess()` itself).
 *
 * NO onConnection HANDLER REGISTERED: every inbound `ws-open` is REJECTED
 * (`ws-reject` with `reason: 'no onConnection handler registered'`),
 * deliberately the OPPOSITE default from `mesh-rpc.mjs`'s missing-handler
 * behavior (which answers `501`, i.e. "here, but nothing implemented") --
 * a WebSocket service with no accept policy at all should not silently
 * accept every inbound connection (an "open door" is a materially worse
 * default than an RPC transport answering "not implemented" to plain
 * request/response calls), so REJECT is the safe default here, still
 * explicit/discoverable rather than a silent hang. `onConnection` THROWING
 * is treated the same as returning falsy -- rejected, never an unhandled
 * rejection, never a crash of the shared `ctx.onIncomingData()` dispatch
 * loop (mirrors `mesh-rpc.mjs`'s `onRequest`-threw handling).
 *
 * ---------------------------------------------------------------------------
 * BINARY ENCODING (the plan's explicit ask: "decide how you encode binary
 * payloads over the JSON envelope, e.g. base64, matching
 * chunk-replication.mjs's established convention"): `send(data)` accepts a
 * `string`, an `ArrayBuffer`, or an `ArrayBuffer` view (any `TypedArray` or
 * `DataView`) -- NOT a `Blob` (a deliberate, documented gap: `Blob` has no
 * universal synchronous-encode story and this class is meant to run
 * identically in Node test environments and browsers; a caller holding a
 * `Blob` should `await blob.arrayBuffer()` first, exactly the same
 * conversion a caller would need for `fetch()`'s body in a
 * `Content-Length`-aware context anyway). A string is sent as
 * `{encoding: 'text', data: theString}` verbatim; binary input is
 * base64-encoded into `{encoding: 'binary', data: base64String}`, using the
 * exact same `toBase64`/`fromBase64` helper shape `chunk-replication.mjs`
 * duplicates per-file rather than sharing (this family's established
 * convention for this one small helper -- see that file's own doc comment).
 * On receipt, a `'text'` message's event `.data` is the string verbatim; a
 * `'binary'` message's event `.data` is a freshly-allocated `ArrayBuffer`
 * (this class's `binaryType` is always effectively `'arraybuffer'` -- there
 * is no `Blob` reconstruction and no `binaryType` property to reconfigure
 * that, another explicit, documented gap versus real `WebSocket`, which
 * defaults to `'blob'`).
 *
 * ---------------------------------------------------------------------------
 * `send()` BEFORE OPEN THROWS; `send()` AFTER CLOSE ALSO THROWS (both
 * documented choices, not oversights):
 *
 *   - Before OPEN (`readyState === CONNECTING`): throws a
 *     `DOMException`/`Error` named `'InvalidStateError'`, EXACTLY matching
 *     real `WebSocket.send()`'s actual behavior (the WHATWG spec mandates
 *     this).
 *   - After CLOSE (`readyState === CLOSING` or `CLOSED`): ALSO throws the
 *     same `InvalidStateError`. This is a DELIBERATE DEVIATION from the
 *     WHATWG spec, per this phase's own explicit brief ("matching real
 *     WebSocket's actual behavior of throwing InvalidStateError if called
 *     before OPEN, not silently dropping" for the before-OPEN case, and
 *     separately, "calling send() after CLOSE throws/rejects rather than
 *     silently doing nothing" for the after-CLOSE case) -- real browsers
 *     silently drop a post-close `send()` (per spec: "If this's ready state
 *     is CLOSING or CLOSED, then return"), which this phase's brief judged
 *     a worse default for mesh code than a loud, discoverable throw. Stated
 *     explicitly here so nobody mistakes this for a spec-compliance bug.
 *
 * ---------------------------------------------------------------------------
 * OPEN TIMEOUT: if no `ws-open-ack`/`ws-reject` arrives within
 * `openTimeoutMs` (default 10000ms, matching `mesh-rpc.mjs`'s
 * `DEFAULT_REQUEST_TIMEOUT_MS` reasoning exactly -- generous enough for a
 * legitimately slow `onConnection` hook, short enough not to hang a caller
 * indefinitely), the connection fires `onerror` then `onclose` with code
 * `1006` (`CLOSE_ABNORMAL`, the same code real `WebSocket` uses for a
 * connection that never completed its opening handshake) and `reason: 'open
 * handshake timed out'`, and transitions straight from `CONNECTING` to
 * `CLOSED` (there is no meaningful `CLOSING` state for a connection that
 * never opened).
 *
 * A `ws-reject` response instead fires `onerror` then `onclose` with code
 * `4403` (a private-use code in RFC 6455's `4000-4999` application-reserved
 * range -- chosen to loosely echo HTTP 403 Forbidden without claiming an
 * IANA-registered meaning it doesn't have) and whatever `reason` the
 * responder's `ws-reject` carried.
 *
 * No browser-only imports at module level.
 */

import { parseMeshRequest } from '@johnhenry/browsermesh-discovery'

/** Default `envelope.type` used to route mesh-websocket payloads on the shared `onIncomingData()` bus. */
const DEFAULT_ENVELOPE_TYPE = 'mesh-websocket'

/** See this file's module doc comment's "OPEN TIMEOUT" section. */
const DEFAULT_OPEN_TIMEOUT_MS = 10000

/** Standard `WebSocket.readyState` numeric values. */
const CONNECTING = 0
const OPEN = 1
const CLOSING = 2
const CLOSED = 3

/**
 * Internal-only construction flag, used by `createMeshWebSocketService()`'s
 * `attach()` to build an already-`OPEN` session handle for an ACCEPTED
 * inbound connection, without duplicating this class's send/close/event
 * machinery in a second class. Not exported -- external callers cannot
 * pass this key, so `new BrowserMeshWebSocket(url, opts)` always goes
 * through the normal client-originates-a-connection path documented above.
 */
const ACCEPTED_SESSION = Symbol('mesh-websocket:accepted-session')

// ---------------------------------------------------------------------------
// Base64 helpers -- deliberately duplicated rather than shared, matching
// this family's established convention of small, self-contained per-file
// helpers (see chunk-replication.mjs's / cloud-storage-backend.mjs's own
// identical duplication).
// ---------------------------------------------------------------------------

/** @param {Uint8Array} bytes @returns {string} */
function toBase64(bytes) {
  if (typeof Buffer !== 'undefined') return Buffer.from(bytes).toString('base64')
  let bin = ''
  for (const b of bytes) bin += String.fromCharCode(b)
  return btoa(bin)
}

/** @param {string} str @returns {Uint8Array} */
function fromBase64(str) {
  if (typeof Buffer !== 'undefined') return new Uint8Array(Buffer.from(str, 'base64'))
  const bin = atob(str)
  const bytes = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i)
  return bytes
}

/** @param {Uint8Array} bytes @returns {ArrayBuffer} A fresh, tightly-sized ArrayBuffer (never a view into a larger/pooled buffer). */
function toFreshArrayBuffer(bytes) {
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength)
}

/**
 * @param {string} message
 * @returns {Error} A `DOMException`-shaped `'InvalidStateError'`, matching
 *   what real `WebSocket.send()` throws, with a plain-`Error` fallback for
 *   environments with no global `DOMException` (older Node).
 */
function invalidStateError(message) {
  if (typeof DOMException !== 'undefined') return new DOMException(message, 'InvalidStateError')
  const err = new Error(message)
  err.name = 'InvalidStateError'
  return err
}

/** Monotonic-ish unique id for correlating a connection's envelopes, matching mesh-rpc.mjs's nextRequestId() shape. */
function nextConnectionId(podId) {
  return `${podId || 'local'}:${Date.now()}:${Math.random().toString(36).slice(2, 10)}`
}

